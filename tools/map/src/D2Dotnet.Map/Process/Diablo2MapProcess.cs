using System.Diagnostics;
using System.Text.Json;
using D2Dotnet.Map.Binary;
using D2Dotnet.Map.Data;
using Microsoft.Extensions.Logging;

namespace D2Dotnet.Map.Process;

/// <summary>Errors reported by the generator process.</summary>
public sealed class MapProcessException(string message, Exception? inner = null) : Exception(message, inner);

/// <summary>
/// One long running native map generator (<c>wine d2-map.exe /app/game</c>) driven over stdin/stdout
/// (upstream <c>Diablo2MapProcess</c> in <c>map.process.ts</c>).
/// </summary>
public sealed class Diablo2MapProcess
{
    private static int _procId;

    private readonly MapProcessOptions _options;
    private readonly LruCache<IReadOnlyList<Diablo2Level>> _mapCache;
    private readonly ILogger _globalLog;
    private readonly string _cwd = Directory.GetCurrentDirectory();

    /// <summary>
    /// Limit the map generation to a single thread (upstream <c>PLimit(1)</c>).
    /// </summary>
    private readonly SemaphoreSlim _queue = new(1, 1);

    /// <summary>Serialises <see cref="StartAsync"/> so concurrent callers do not spawn two generators.</summary>
    private readonly SemaphoreSlim _startLock = new(1, 1);

    private RunningProcess? _process;

    public Diablo2MapProcess(
        Diablo2MpqData mpq,
        string mapCommand,
        MapProcessOptions options,
        LruCache<IReadOnlyList<Diablo2Level>> mapCache,
        ILogger globalLog)
    {
        Mpq = mpq;
        MapCommand = mapCommand;
        _options = options;
        _mapCache = mapCache;
        _globalLog = globalLog;
        Id = Interlocked.Increment(ref _procId) - 1;
    }

    /// <summary>Number of maps generated by this process.</summary>
    public int GeneratedCount { get; private set; }

    public EventHub Events { get; } = new();
    public Diablo2MpqData Mpq { get; }
    public string MapCommand { get; }
    public int Id { get; }

    public bool IsRunning => _process != null;

    /// <summary>OS process id of the running generator, if any.</summary>
    public int? ProcessId => _process?.Process.Id;

    /// <summary>Get the version of WINE that is being used.</summary>
    public async Task<string> VersionAsync(ILogger log)
    {
        var versionResponse = await ChildProcess.RunAsync(_options.WineCommand, ["--version"]).ConfigureAwait(false);
        var version = versionResponse.Stdout;
        log.LogInformation("MapProcess:WineVersion {Version} {Command}", version, _options.WineCommand);
        return version;
    }

    /// <summary>Start the map process waiting for the <c>init</c> event before allowing anything to continue.</summary>
    public async Task StartAsync(ILogger log)
    {
        if (IsRunning) return;
        await _startLock.WaitAsync().ConfigureAwait(false);
        try
        {
            if (IsRunning) return;
            GeneratedCount = 0;

            string[] args = [MapCommand, _options.Diablo2Path];
            log.LogInformation("MapProcess:Starting {Proc} {WineArgs}", Id, args);

            var psi = new ProcessStartInfo(_options.WineCommand)
            {
                RedirectStandardInput = true,
                RedirectStandardOutput = true,
                RedirectStandardError = true,
                UseShellExecute = false,
                WorkingDirectory = _cwd,
            };
            foreach (var a in args) psi.ArgumentList.Add(a);
            // Only WINEPREFIX is passed through, and wine debug logging is disabled
            psi.Environment.Clear();
            var winePrefix = Environment.GetEnvironmentVariable("WINEPREFIX");
            if (winePrefix != null) psi.Environment["WINEPREFIX"] = winePrefix;
            psi.Environment["WINEDEBUG"] = "-all";

            using var initCancel = new CancellationTokenSource();
            var init = OnceAsync(MapGenMessage.Init, null, initCancel.Token);

            System.Diagnostics.Process proc;
            try
            {
                proc = System.Diagnostics.Process.Start(psi) ?? throw new MapProcessException("Failed to start command");
            }
            catch (Exception error)
            {
                await initCancel.CancelAsync().ConfigureAwait(false);
                await init.ContinueWith(_ => { }, TaskScheduler.Default).ConfigureAwait(false);
                log.LogCritical(error, "MapProcess:Died {Proc}", Id);
                throw error as MapProcessException ?? new MapProcessException("Failed to start command", error);
            }

            var running = new RunningProcess(proc);
            _process = running;
            proc.StandardInput.AutoFlush = true;
            proc.ErrorDataReceived += (_, e) => OnStderr(running, e.Data, log);
            proc.BeginErrorReadLine();

            log.LogInformation("MapProcess:Started {Proc} {ProcessId}", Id, proc.Id);
            _ = Task.Run(() => ReadStdoutAsync(running, log));

            await init.ConfigureAwait(false);
        }
        finally
        {
            _startLock.Release();
        }
    }

    private void OnStderr(RunningProcess running, string? data, ILogger log)
    {
        if (data == null) return;
        var line = data.Trim();
        if (line.Contains("FS volume label and serial are not available", StringComparison.Ordinal)) return;
        _globalLog.LogDebug("MapProcess:stderr {Proc} {Data}", Id, line);
        if (line.Contains("We got a big Error here", StringComparison.Ordinal) && _process == running) Stop(log);
    }

    private async Task ReadStdoutAsync(RunningProcess running, ILogger log)
    {
        var proc = running.Process;
        try
        {
            while (await proc.StandardOutput.ReadLineAsync().ConfigureAwait(false) is { } line)
            {
                OnLine(line);
            }
        }
        catch (Exception e) when (e is IOException or ObjectDisposedException or InvalidOperationException)
        {
            // stream closed
        }

        int? exitCode = null;
        try
        {
            await proc.WaitForExitAsync().ConfigureAwait(false);
            if (!running.Killed) exitCode = proc.ExitCode;
        }
        catch (InvalidOperationException)
        {
            // process was disposed
        }

        if (_process == running) _process = null;
        Events.Emit(MapGenMessage.Close);
        if (exitCode > 0) log.LogCritical("MapProcess:Closed {Proc} {ExitCode}", Id, exitCode);
        proc.Dispose();
    }

    /// <summary>Dispatch one stdout line from the generator.</summary>
    internal void OnLine(string line)
    {
        var type = MapGenMessage.Classify(line, out var json);
        if (type == null) return;
        try
        {
            Events.Emit(type, json);
        }
        catch (Exception e)
        {
            _globalLog.LogError(e, "MapProcess:Line:Failed {Proc} {Type}", Id, type);
        }
    }

    /// <summary>Wait for the next event of a type, optionally running <paramref name="cb"/> after subscribing.</summary>
    /// <exception cref="TimeoutException">No event within <see cref="MapProcessOptions.ProcessTimeout"/>.</exception>
    public async Task<JsonElement> OnceAsync(string e, Action? cb = null, CancellationToken cancellationToken = default)
    {
        var tcs = new TaskCompletionSource<JsonElement>(TaskCreationOptions.RunContinuationsAsynchronously);
        Action<JsonElement> handler = data => tcs.TrySetResult(data);
        Events.Once(e, handler);
        cb?.Invoke();

        var timeout = _options.ProcessTimeout;
        try
        {
            return await tcs.Task.WaitAsync(timeout, cancellationToken).ConfigureAwait(false);
        }
        catch (TimeoutException)
        {
            Events.Off(e, handler);
            throw new TimeoutException($"Event: {e} Timeout after {timeout.TotalMilliseconds}ms");
        }
        catch (OperationCanceledException)
        {
            Events.Off(e, handler);
            throw;
        }
    }

    /// <summary>Kill the generator.</summary>
    public void Stop(ILogger log)
    {
        var running = _process;
        if (running == null) return;
        log.LogInformation("MapProcess:Stop {Proc} {ProcessId}", Id, running.Process.Id);
        running.Killed = true;
        try
        {
            running.Process.Kill();
        }
        catch (InvalidOperationException)
        {
            // already exited
        }
        _process = null;
    }

    /// <summary>Send a <c>$cmd value</c> command and check the generator echoed the new value.</summary>
    public async Task CommandAsync(string cmd, double value, ILogger log)
    {
        var startTime = Stopwatch.GetTimestamp();
        if (_process == null) await StartAsync(log).ConfigureAwait(false);
        var command = $"${cmd} {JsNumber.ToJsString(value)}\n";
        var res = await OnceAsync(MapGenMessage.Info, () => Write(command)).ConfigureAwait(false);
        if (!res.TryGetProperty(cmd, out var echoed) || echoed.ValueKind != JsonValueKind.Number || echoed.GetDouble() != value)
        {
            throw new MapProcessException($"Failed to set {cmd}={JsNumber.ToJsString(value)} (output: {res.GetRawText()}: {command})");
        }

        log.LogTrace("MapProcess:Command {Cmd} {Value} {Duration}", cmd, value, Stopwatch.GetElapsedTime(startTime).TotalMilliseconds);
    }

    private void Write(string command)
    {
        var running = _process;
        if (running == null) return;
        try
        {
            running.Process.StandardInput.Write(command);
        }
        catch (Exception e) when (e is IOException or ObjectDisposedException or InvalidOperationException)
        {
            _globalLog.LogDebug(e, "MapProcess:Write:Failed {Proc}", Id);
        }
    }

    /// <summary>Generate (or fetch from the shared cache) all levels of a seed/difficulty/act; act -1 is every act.</summary>
    public async Task<IReadOnlyList<Diablo2Level>> MapAsync(double seed, int difficulty, int actId, ILogger log)
    {
        var mapKey = $"{JsNumber.ToJsString(seed)}_{difficulty}_{actId}";
        var cacheData = _mapCache.Get(mapKey);
        if (cacheData != null) return cacheData;

        await _queue.WaitAsync().ConfigureAwait(false);
        try
        {
            var mapResult = await GetMapsAsync(seed, difficulty, actId, log).ConfigureAwait(false);
            _mapCache.Set(mapKey, mapResult);
            return mapResult;
        }
        finally
        {
            _queue.Release();
        }
    }

    private async Task<IReadOnlyList<Diablo2Level>> GetMapsAsync(double seed, int difficulty, int actId, ILogger log, int attempt = 0)
    {
        if (GeneratedCount > _options.MaxMapsToGenerate)
        {
            log.LogWarning("GenerateMap:Restart");
            GeneratedCount = 0;
            Stop(log);
            await StartAsync(log).ConfigureAwait(false);
        }

        if (!IsRunning) await StartAsync(log).ConfigureAwait(false);

        await CommandAsync("seed", seed, log).ConfigureAwait(false);
        await CommandAsync("difficulty", difficulty, log).ConfigureAwait(false);
        if (actId > -1) await CommandAsync("act", actId, log).ConfigureAwait(false);

        GeneratedCount++;
        var seedHex = Hex.ToHex((long)seed, 8);
        log.LogInformation("GenerateMap:Start {Proc} {Seed} {Difficulty} {Generated}", Id, seedHex, difficulty, GeneratedCount);
        var maps = new OrderedDictionary<int, Diablo2Level>();
        var tcs = new TaskCompletionSource<IReadOnlyList<Diablo2Level>>(TaskCreationOptions.RunContinuationsAsynchronously);

        void NewMap(JsonElement msg)
        {
            var level = MapGenMessage.ParseLevel(msg);
            log.LogTrace("GenerateMap:GotMap {Proc} {MapId}", Id, level.Id);
            maps[level.Id] = FixMap(level);
        }

        void LogLine(JsonElement json)
        {
            if (!json.TryGetProperty("level", out var level) || level.ValueKind != JsonValueKind.Number || level.GetDouble() < 30) return;
            var msg = json.TryGetProperty("msg", out var m) ? m.ToString() : null;
            log.LogInformation("MapProcess:Log {Proc} {Log} {Data}", Id, msg, json.GetRawText());
        }

        void Done(JsonElement _)
        {
            Events.Off(MapGenMessage.Map, NewMap);
            Events.Off(MapGenMessage.Close, ErrorHandle);
            Events.Off(MapGenMessage.Log, LogLine);
            log.LogTrace("GenerateMap:Generated {Proc} {Count}", Id, maps.Count);
            tcs.TrySetResult([.. maps.Values]);
        }

        void ErrorHandle(JsonElement closeEvent)
        {
            Events.Off(MapGenMessage.Map, NewMap);
            Events.Off(MapGenMessage.Log, LogLine);
            Events.Off(MapGenMessage.Done, Done);
            log.LogInformation("GenerateMap:Error {Proc} {Seed} {Difficulty} {Attempt}", Id, seedHex, difficulty, attempt);
            if (attempt < _options.MaxAttempts)
            {
                _ = RetryAsync();
            }
            else
            {
                log.LogInformation("GenerateMap:Reject {Attempt} {MaxAttempts}", attempt, _options.MaxAttempts);
                tcs.TrySetException(new MapProcessException("MapProcess:Closed"));
            }
        }

        async Task RetryAsync()
        {
            try
            {
                tcs.TrySetResult(await GetMapsAsync(seed, difficulty, actId, log, attempt + 1).ConfigureAwait(false));
            }
            catch (Exception e)
            {
                tcs.TrySetException(e);
            }
        }

        Events.Once(MapGenMessage.Close, ErrorHandle);
        Events.On(MapGenMessage.Map, NewMap);
        Events.On(MapGenMessage.Log, LogLine);
        Events.Once(MapGenMessage.Done, Done);
        Write("$map\n");

        return await tcs.Task.ConfigureAwait(false);
    }

    /// <summary>Correct the names of npcs, objects and exits using the MPQ data.</summary>
    public Diablo2Level FixMap(Diablo2Level map)
    {
        if (Mpq.Levels.TryGetValue(map.Id, out var mpqLevel)) map.Name = JsNumber.TrimJs(mpqLevel.Name);
        foreach (var obj in map.Objects)
        {
            if (obj.Type == Diablo2LevelObjectType.Npc)
            {
                if (obj.Id >= Mpq.Monsters.Size)
                {
                    var superId = obj.Id - Mpq.Monsters.Size;
                    if (superId < Mpq.Monsters.SuperUniques.Count)
                    {
                        obj.Name = Mpq.Monsters.SuperUniqueName(superId);
                        obj.IsSuperUnique = true;
                        obj.SuperId = superId;
                    }
                }
                else
                {
                    obj.Name = TrimOrNull(Mpq.Monsters.Name(obj.Id));
                }
            }

            if (obj.Type == Diablo2LevelObjectType.Object)
            {
                obj.Name = Mpq.Objects.TryGetValue(obj.Id, out var o) ? JsNumber.TrimJs(o.Name) : null;
            }

            if (obj.Type == Diablo2LevelObjectType.Exit)
            {
                obj.Name = Mpq.Levels.TryGetValue(obj.Id, out var l) ? JsNumber.TrimJs(l.Name) : null;
            }
        }

        return map;
    }

    private static string? TrimOrNull(string? s) => s == null ? null : JsNumber.TrimJs(s);

    private sealed class RunningProcess(System.Diagnostics.Process process)
    {
        public System.Diagnostics.Process Process { get; } = process;
        public volatile bool Killed;
    }
}
