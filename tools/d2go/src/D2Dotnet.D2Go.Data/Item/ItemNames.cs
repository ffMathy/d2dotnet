    /// <summary>The name of item id <paramref name="itemNumber"/> (Go <c>GetNameByEnum</c>).</summary>
    /// <exception cref="ArgumentOutOfRangeException"><paramref name="itemNumber"/> is not an index of <see cref="Names"/> (Go panics).</exception>
    public static ItemName GetNameByEnum(uint itemNumber) =>
        itemNumber < (uint)Names.Count
            ? new ItemName(Names[(int)itemNumber])
            : throw new ArgumentOutOfRangeException(nameof(itemNumber), itemNumber, "No item has this id.");

    /// <summary>The id of the first item whose name equals <paramref name="itemName"/> ignoring case, or -1 (Go <c>GetIDByName</c>).</summary>
    public static int GetIdByName(string itemName)
    {
        for (var i = 0; i < Names.Count; i++)
        {
            if (GoStrings.EqualFold(Names[i], itemName))
                return i;
        }

        return -1;
    }
